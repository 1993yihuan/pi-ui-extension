/**
 * User-visible copy. Chinese when the locale says zh; English otherwise.
 * `PI_UI_LANG` (or `PI_UI_LANGUAGE`) overrides `LC_ALL`, then `LC_MESSAGES`, then `LANG`.
 */
export type UiLanguage = "en" | "zh";

const CHINESE = /^(?:zh|chinese)(?:$|[_@.-])/;
const ENGLISH = /^(?:en|english)(?:$|[_@.-])/;
const LOCALE_KEYS = ["LC_ALL", "LC_MESSAGES", "LANG"] as const;

function localeTag(value: string | undefined): string | undefined {
  const parts = value?.trim()?.split(/[.:]/);
  const tag = parts?.[0]?.trim().toLowerCase().replace(/-/g, "_");
  return tag || undefined;
}

/** zh when the override or POSIX locale indicates Chinese; otherwise en. */
export function selectLanguage(env: NodeJS.ProcessEnv = process.env): UiLanguage {
  const override = localeTag(env.PI_UI_LANG) ?? localeTag(env.PI_UI_LANGUAGE);
  if (override) {
    if (CHINESE.test(override)) return "zh";
    if (ENGLISH.test(override)) return "en";
  }
  for (const key of LOCALE_KEYS) {
    const tag = localeTag(env[key]);
    if (!tag) continue;
    if (tag === "c" || tag === "posix") return "en";
    if (CHINESE.test(tag)) return "zh";
    if (/^[a-z]{2,}(?:_|$)/.test(tag)) return "en";
  }
  return "en";
}

